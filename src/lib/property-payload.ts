import type { PropertyFormValues } from "@/components/admin/PropertyForm";

const num = (s: string) => (s === "" || s == null ? null : Number(s));

export function toPropertyPayload(v: PropertyFormValues) {
  return {
    title: v.title,
    description: v.description || null,
    property_type: v.property_type,
    transaction_type: v.transaction_type,
    price: num(v.price),
    condo_fee: num(v.condo_fee),
    iptu: num(v.iptu),
    city: v.city,
    state: v.state || null,
    neighborhood: v.neighborhood || null,
    address: v.address || null,
    latitude: num(v.latitude),
    longitude: num(v.longitude),
    bedrooms: num(v.bedrooms),
    suites: num(v.suites),
    bathrooms: num(v.bathrooms),
    parking_spaces: num(v.parking_spaces),
    built_area: num(v.built_area),
    total_area: num(v.total_area),
    land_area: num(v.land_area),
    cover_image: v.cover_image || null,
    gallery: v.gallery,
    videos: v.videos,
    virtual_tour_url: v.virtual_tour_url || null,
    features: v.features,
    agent_id: v.agent_id || null,
    status: v.status || "disponivel",
    archived: !!v.archived,
    published: v.published,
    is_featured: v.is_featured,
    is_launch: v.is_launch,
    is_opportunity: v.is_opportunity,
    is_new: v.is_new,
    is_mcmv: v.is_mcmv,
  };
}

export function fromPropertyRow(data: any): Partial<PropertyFormValues> {
  return {
    title: data.title ?? "",
    description: data.description ?? "",
    property_type: data.property_type ?? "casa",
    transaction_type: data.transaction_type ?? "venda",
    price: data.price?.toString() ?? "",
    condo_fee: data.condo_fee?.toString() ?? "",
    iptu: data.iptu?.toString() ?? "",
    city: data.city ?? "Tatuí",
    state: data.state ?? "SP",
    neighborhood: data.neighborhood ?? "",
    address: data.address ?? "",
    latitude: data.latitude?.toString() ?? "",
    longitude: data.longitude?.toString() ?? "",
    bedrooms: data.bedrooms?.toString() ?? "",
    suites: data.suites?.toString() ?? "",
    bathrooms: data.bathrooms?.toString() ?? "",
    parking_spaces: data.parking_spaces?.toString() ?? "",
    built_area: data.built_area?.toString() ?? "",
    total_area: data.total_area?.toString() ?? "",
    land_area: data.land_area?.toString() ?? "",
    cover_image: data.cover_image ?? "",
    gallery: (data.gallery as string[]) ?? [],
    videos: (data.videos as string[]) ?? [],
    virtual_tour_url: data.virtual_tour_url ?? "",
    features: (data.features as string[]) ?? [],
    agent_id: data.agent_id ?? "",
    status: data.status ?? "disponivel",
    archived: !!data.archived,
    published: data.published,
    is_featured: data.is_featured,
    is_launch: data.is_launch,
    is_opportunity: data.is_opportunity,
    is_new: data.is_new,
    is_mcmv: data.is_mcmv,
  };
}
